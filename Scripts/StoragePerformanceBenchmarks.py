"""Run some benchmarks of our current storage system to detect hardware or software related performance issues.

This module is organized around three concepts: test data generation, write/read benchmark functions, and
a JSON-backed benchmark log used to persist and compare results across runs.

Test data is generated by ``create_test_data`` to approximate realistic detector acquisitions using a
``PerformanceTestSettings`` instance, which describes the microscope and detector parameters (beam current,
detector shape, exposure time, collection shape, and sequence length) used to compute a realistic count
distribution. Each benchmark function (for example ``write_hdf5_uncompressed`` or
``write_hdf5_uncompressed_acquisition_loop``) accepts a ``PerformanceTestSettings`` instance and the generated
test data, performs a timed write or read operation, and records the configuration and elapsed time as a
``LogEntry`` in a ``BenchmarkLog``. Read benchmarks such as ``create_virtual_bf_images`` and
``slice_and_sum_collection_axis`` operate on the file names produced by the write benchmarks and reconstruct
the corresponding ``LogEntry`` from the generated file name via ``LogEntry.from_file_name``.

To run the benchmarks directly, execute this script. The ``__main__`` block creates a ``PerformanceTestSettings``
instance, generates test data, runs the write benchmarks, runs the read benchmarks against the resulting files,
and prints a summary of the results as pandas dataframes via ``BenchmarkLog.as_pandas_dataframe``.

To extend this module with a new test for a different data format (for example, a new file format or
compression scheme), add a new write function following the pattern of ``write_hdf5_uncompressed``: accept a
``PerformanceTestSettings`` instance, the test data, and an optional ``BenchmarkLog``; build a ``LogEntry``
describing the configuration under test; time the relevant operations; log the result via ``BenchmarkLog.log``;
and return the generated file name so it can be passed to the read benchmarks. If the new format requires
additional read-side handling, you will need to change the two read benchmark functions,
``create_virtual_bf_images`` and ``slice_and_sum_collection_axis``.
"""


