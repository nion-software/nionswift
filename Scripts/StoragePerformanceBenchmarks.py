def create_virtual_bf_images(benchmark_settings: PerformanceTestSettings, file_names: set[str], benchmark_log: BenchmarkLog | None = None):
    # Sum the central part of the detector for each frame in the collection

    for filename in file_names:
        fullpath = os.path.join(benchmark_settings.folder, filename)
        hdf5_file = h5py.File(fullpath, 'r')
        opened_dataset = hdf5_file['data']

        read_log_entry = LogEntry.from_file_name(filename)

        dset = opened_dataset
        dset_shape = dset.shape
        vbf_slices = (..., slice(int(dset_shape[2]*0.25), int(dset_shape[2]*0.75)), slice(int(dset_shape[3]*0.25), int(dset_shape[3]*0.75)))

        t0 = time.perf_counter()
        sliced = dset[vbf_slices]
        t1 = time.perf_counter()
        integrated = np.sum(sliced, axis=(-1, -2))
        t2 = time.perf_counter()

        print(f'Slice data: {t1 - t0:.2f} s\nIntegrate: {t2 - t1:.2f} s.')
        if benchmark_log:
            benchmark_log.log(dataclasses.replace(read_log_entry, aux_data='compute_vbf'), float(t2 - t0))
        hdf5_file.close()


def slice_and_sum_collection_axis(benchmark_settings: PerformanceTestSettings, file_names: set[str], benchmark_log: BenchmarkLog | None = None):
    # Slice and sum along the collection axes
    for filename in file_names:
        fullpath = os.path.join(benchmark_settings.folder, filename)
        hdf5_file = h5py.File(fullpath, 'r')
        opened_dataset = hdf5_file['data']

        read_log_entry = LogEntry.from_file_name(filename)

        dset = opened_dataset
        dset_shape = dset.shape
        collection_slices = (slice(int(dset_shape[0]*0.25), int(dset_shape[0]*0.75)), slice(int(dset_shape[1]*0.25), int(dset_shape[1]*0.75)))

        t0 = time.perf_counter()
        sliced = dset[collection_slices]
        t1 = time.perf_counter()
        integrated = np.sum(sliced, axis=(0, 1))
        t2 = time.perf_counter()

        print(f'Slice data: {t1 - t0:.2f} s\nIntegrate: {t2 - t1:.2f} s.')
        if benchmark_log:
            benchmark_log.log(dataclasses.replace(read_log_entry, aux_data='slice_and_sum_collection'), float(t2 - t0))
        hdf5_file.close()


def clean_up_test_data_files(benchmark_settings: PerformanceTestSettings, file_names: set[str]):
    for file_name in file_names:
        try:
            os.remove(os.path.join(benchmark_settings.folder, file_name))
        except FileNotFoundError:
            pass


